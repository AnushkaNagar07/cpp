// calculating various bitwise operations

# include <iostream>
using namespace std;
int main(){
    cout<<"6 & 10= "<<(6 & 10)<<endl ;    // bitwise and
    cout<<"6 | 10= "<<(6 | 10)<<endl ;      // bitwise or
    cout<<"6 ^ 10= "<<(6 ^ 10 )<<endl;      // bitwise XOR
    cout<<"10 << 2= "<<(10 << 2)<<endl;     // bitwise left shift
    cout<<"10 >> 1= "<<(10 >> 1)<<endl;       // bitwise right shift
    return 0;
}